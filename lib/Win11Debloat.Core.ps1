    Set-RegValue 'HKLM:\SOFTWARE\Policies\Microsoft\WindowsStore' 'AutoDownload' 2
    Set-RegValue 'HKLM:\SOFTWARE\Policies\Microsoft\WindowsStore' 'DisableStoreApps' 0

    if ($DisableTelemetry -or $Action -eq 'Privacy') {
