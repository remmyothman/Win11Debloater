.SYNOPSIS
    Win11Debloat.Core.ps1 - shared function library for Win11Debloater (console + GUI).

.DESCRIPTION
    Dot-source this file; do not run it. It only defines functions and state.
    The calling script owns the switches the functions read:
        $DryRun, $Aggressive, $KeepXbox, $KeepMdmService, $NoRestorePoint
    Unset switches are treated as false, so the GUI only has to set $DryRun.

